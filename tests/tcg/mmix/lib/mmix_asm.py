_ASM_CONSTANT_NAMES = tuple(
    name for name, value in globals().items()
    if name.isupper() and isinstance(value, int)
)

__all__ = [
    "branch",
    "halt",
    "insn",
    "jump",
    "set_octa",
    "wyde",
    *_ASM_CONSTANT_NAMES,
]


def insn(op, x=0, y=0, z=0):
    return bitstruct.pack("u8u8u8u8", op, x, y, z)


def branch(op, x, yz):
    return bitstruct.pack("u8u8u16", op, x, yz)


def jump(op, xyz):
    return bitstruct.pack("u8u24", op, xyz)


def wyde(op, x, yz):
    return bitstruct.pack("u8u8u16", op, x, yz)


def halt():
    return insn(TRAP, 0, 0, 0)


def set_octa(reg, value):
    return [
        wyde(SETH, reg, (value >> 48) & 0xffff),
        wyde(INCMH, reg, (value >> 32) & 0xffff),
        wyde(INCML, reg, (value >> 16) & 0xffff),
        wyde(INCL, reg, value & 0xffff),
    ]
